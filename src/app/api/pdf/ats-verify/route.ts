/**
 * POST /api/pdf/ats-verify
 *
 * Runs the ATS text-layer verification on a generated resume PDF.
 * Calls src/lib/pdf/ats-verify.py via Node's child_process.
 * Stores the report on the Application and returns it.
 *
 * Body: { applicationId: string }
 * Returns: AtsReport JSON
 */

import "server-only";

import { spawn } from "child_process";
import path from "path";
import { NextResponse } from "next/server";

import { loadApplication, loadDocuments } from "@/lib/application-documents";
import { prisma } from "@/lib/prisma";
import { loadProfile } from "@/lib/profile-data";
import { getSession } from "@/lib/auth/session";

const ATS_SCRIPT = path.join(process.cwd(), "src", "lib", "pdf", "ats-verify.py");
const PYTHON_CMD = process.env.PYTHON_BIN || (process.platform === "win32" ? "python" : "python3");

async function runAtsScript(input: {
  pdf_path: string;
  job_keywords: string[];
  contact_name: string;
  contact_email: string;
  contact_phone: string;
}): Promise<Record<string, unknown>> {
  return new Promise((resolve, reject) => {
    const proc = spawn(PYTHON_CMD, [ATS_SCRIPT], {
      stdio: ["pipe", "pipe", "pipe"],
    });

    let stdout = "";
    let stderr = "";

    proc.stdout.on("data", (d: Buffer) => { stdout += d.toString(); });
    proc.stderr.on("data", (d: Buffer) => { stderr += d.toString(); });

    proc.on("close", (code) => {
      if (!stdout.trim()) {
        reject(new Error(`ATS script produced no output (exit ${code}): ${stderr}`));
        return;
      }
      try {
        resolve(JSON.parse(stdout));
      } catch {
        reject(new Error(`ATS script output is not JSON: ${stdout.slice(0, 200)}`));
      }
    });

    proc.on("error", (err) => reject(err));
    proc.stdin.write(JSON.stringify(input));
    proc.stdin.end();
  });
}

/** Extract keywords from a job posting (simple TF-IDF-like frequency filter). */
function extractKeywords(postingText: string, maxKeywords = 40): string[] {
  const STOP = new Set([
    "the", "and", "or", "in", "at", "to", "a", "an", "of", "for", "with",
    "is", "are", "we", "you", "your", "our", "will", "be", "on", "as",
    "have", "experience", "skills", "team", "work", "role", "position",
    "company", "opportunity", "join", "looking", "seeking", "candidate",
    "ability", "strong", "excellent", "knowledge", "understanding", "plus",
    "including", "etc", "also", "both", "all", "any", "new", "other",
    "this", "that", "who", "what", "how", "not", "do", "from", "by",
  ]);

  const words = postingText.toLowerCase().match(/\b[a-z][a-z\-.+#]{2,}\b/g) ?? [];
  const freq = new Map<string, number>();
  for (const w of words) {
    if (!STOP.has(w)) freq.set(w, (freq.get(w) ?? 0) + 1);
  }

  // Also include multi-word technical terms (2-3 word phrases)
  const phrases = postingText.match(/\b(?:[A-Z][a-z]*\s+){1,2}[A-Z][a-z]+\b/g) ?? [];
  for (const p of phrases) {
    const key = p.toLowerCase();
    freq.set(key, (freq.get(key) ?? 0) + 2); // weight phrases higher
  }

  return [...freq.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, maxKeywords)
    .map(([w]) => w);
}

export async function POST(request: Request) {
  if (!(await getSession())) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  let body: { applicationId?: string };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const { applicationId } = body;
  if (!applicationId) {
    return NextResponse.json({ error: "applicationId is required" }, { status: 400 });
  }

  // Load application data
  let docs: Awaited<ReturnType<typeof loadDocuments>>;
  try {
    docs = await loadDocuments(applicationId);
  } catch {
    return NextResponse.json({ error: "Application not found" }, { status: 404 });
  }

  const { application, profile } = docs;

  // Find the resume PDF path (generated by /api/pdf)
  // The PDF is rendered into /tmp/dossier-pdfs/ by the PDF renderer
  const pdfPath = path.join(process.env.PDF_DIR ?? "/tmp/dossier-pdfs", `${applicationId}-resume.pdf`);

  const keywords = extractKeywords(application.postingText);

  let report: Record<string, unknown>;
  try {
    report = await runAtsScript({
      pdf_path: pdfPath,
      job_keywords: keywords,
      contact_name: profile.basics.name ?? "",
      contact_email: profile.basics.email ?? "",
      contact_phone: profile.basics.phone ?? "",
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    // Return a "not available" report rather than a hard error
    report = {
      extractor: "unavailable",
      pages: 0,
      passed: false,
      error: message,
      warnings: [
        "ATS verification unavailable: Python 3 and pypdf are required (pip install pypdf).",
        message,
      ],
    };
  }

  // Persist the report to the database
  await prisma.application.update({
    where: { id: applicationId },
    data: { atsReport: report },
  });

  return NextResponse.json(report);
}
